#!/usr/bin/env node
// ai-team — turns the lessons file (conf DOCS_LESSONS, `L-<n>` lines the spec-writer promotes at archive) into
// Claude Code rules in .claude/rules/, so a lesson reaches the agent when it opens the code it is about, whether or
// not the agent remembers to read the file (and again after a compaction).
//
//   node .claude/ai-team/dashboard/lessons.mjs [--project DIR] [--force]
//
// A lesson line: `- L-<n> · <rule> · origin … [· scope: backend | frontend | any]`. No scope = any.
//   any       → .claude/rules/ai-team-lessons.md, no `paths:` (loaded at the start of every session and subagent)
//   backend   → .claude/rules/ai-team-lessons-backend.md, `paths: <BACKEND_DIR>/**`
//   frontend  → .claude/rules/ai-team-lessons-frontend.md, `paths: <FRONTEND_DIR>/**`
// Claude Code matches a file of a worktree in .claude/worktrees/ relative to that worktree: for the root repository
// that is the project path (`frontend/src/a.ts`), but for a package with its own repository (`*_OWN_REPO=1`) it is
// the path inside the package (`src/a.ts`), so that front's rule gets `**` instead (it then loads for any file,
// as all lessons did before). A front whose folder is the root (`.`) also gets `**`.
// Only rewrites when the lessons file is newer than the rules (or --force); removes our rule files that no longer have
// lessons. Called by the installer (--render) and by hook.mjs on SubagentStart. Never throws from syncLessonRules.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readConf } from './conf.mjs';

export const PREFIX = 'ai-team-lessons';
const SCOPES = ['any', 'backend', 'frontend'];
const LINE = /^-\s+(L-\d+)\s+·\s+(.+)$/;

// lessons file text → [{ id, rule, scope }]
export function parseLessons(text) {
  const out = [];
  for (const raw of String(text || '').split('\n')) {
    const m = LINE.exec(raw.trim());
    if (!m) continue;
    const fields = m[2].split(/\s+·\s+/);
    let scope = 'any';
    const sc = fields.findIndex((f) => /^scope:\s*/i.test(f));
    if (sc >= 0) { const v = fields[sc].replace(/^scope:\s*/i, '').trim().toLowerCase(); if (SCOPES.includes(v)) scope = v; fields.splice(sc, 1); }
    const rule = fields.filter((f) => !/^origin\b/i.test(f)).join(' · ').trim();
    if (rule) out.push({ id: m[1], rule, scope });
  }
  return out;
}

const dirOf = (conf, front) => String(conf[`${front.toUpperCase()}_DIR`] || '').replace(/\/+$/, '');
// the `paths:` globs of a front's rule (null = no paths)
export function scopePaths(scope, conf) {
  if (scope === 'any') return null;
  const dir = dirOf(conf, scope);
  if (!dir || dir === '.') return ['**'];
  return conf[`${scope.toUpperCase()}_OWN_REPO`] === '1' ? ['**'] : [`${dir}/**`];
}

// lessons + conf → { 'ai-team-lessons.md': text, … } (only scopes that have lessons)
export function renderRules(lessons, conf, source) {
  const files = {};
  for (const scope of SCOPES) {
    const ls = lessons.filter((l) => l.scope === scope);
    if (!ls.length) continue;
    const globs = scopePaths(scope, conf);
    const head = globs ? `---\npaths:\n${globs.map((g) => `  - "${g}"`).join('\n')}\n---\n` : '';
    const title = scope === 'any' ? 'Lessons from past reviews' : `Lessons from past reviews (${scope})`;
    files[`${PREFIX}${scope === 'any' ? '' : `-${scope}`}.md`] = `${head}<!-- generated by ai-team from ${source}; edit that file, not this one -->\n# ${title}\n\n`
      + `Mistakes the reviewer caught in more than one change of this project. Each applies whenever its case comes up; a finding that repeats one is blocking.\n\n`
      + ls.map((l) => `- ${l.id} · ${l.rule}`).join('\n') + '\n';
  }
  return files;
}

// writes/removes the rule files; returns { written: [...], removed: [...] } or null when nothing to do
export function syncLessonRules(projectDir, { force = false, conf = null } = {}) {
  try {
    const c = conf || readConf(projectDir);
    const rel = c.DOCS_LESSONS;
    if (!rel) return null;
    const src = path.resolve(projectDir, rel), rulesDir = path.join(projectDir, '.claude', 'rules');
    let srcStat = null; try { srcStat = fs.statSync(src); } catch { /* no lessons yet */ }
    let ours = []; try { ours = fs.readdirSync(rulesDir).filter((f) => f.startsWith(PREFIX) && f.endsWith('.md')); } catch { /* no rules dir */ }
    if (!force && srcStat && ours.length && ours.every((f) => { try { return fs.statSync(path.join(rulesDir, f)).mtimeMs >= srcStat.mtimeMs; } catch { return false; } })) return null;
    if (!srcStat && !ours.length) return null;
    const files = srcStat ? renderRules(parseLessons(fs.readFileSync(src, 'utf8')), c, rel) : {};
    const written = [], removed = [];
    if (Object.keys(files).length) fs.mkdirSync(rulesDir, { recursive: true });
    for (const [name, text] of Object.entries(files)) {
      const f = path.join(rulesDir, name);
      let cur = null; try { cur = fs.readFileSync(f, 'utf8'); } catch { /* new */ }
      if (cur !== text) { fs.writeFileSync(f, text); written.push(name); }
      else { const now = new Date(); fs.utimesSync(f, now, now); }   // same content: mark as fresh so the next check is a stat
    }
    for (const name of ours) if (!(name in files)) { fs.unlinkSync(path.join(rulesDir, name)); removed.push(name); }
    return { written, removed };
  } catch { return null; }
}

// realpath: on macOS /var is a link to /private/var (import.meta.url is already resolved)
if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const a = process.argv.slice(2), i = a.indexOf('--project');
  const proj = i >= 0 && a[i + 1] ? path.resolve(a[i + 1]) : (process.env.CLAUDE_PROJECT_DIR || process.cwd());
  const r = syncLessonRules(proj, { force: a.includes('--force') });
  if (r && (r.written.length || r.removed.length)) console.log(`lesson rules: ${[...r.written.map((f) => `wrote .claude/rules/${f}`), ...r.removed.map((f) => `removed .claude/rules/${f}`)].join(', ')}`);
}
