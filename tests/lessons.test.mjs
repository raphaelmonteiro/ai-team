// lessons.mjs tests: lesson lines → .claude/rules files, scopes, folders, own repositories, refresh and cleanup.
//   node tests/lessons.test.mjs
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { parseLessons, scopePaths, renderRules, syncLessonRules } from '../dashboard/lessons.mjs';
import { runHook } from '../dashboard/hook.mjs';

const TEXT = `# Lições

Append-only.

- L-1 · Meça com o ESLint · origin R1/a, R2/b
- L-2 · Use \`utils/x\` · origin R3/c · scope: frontend
- L-3 · No \`any\` no backend · origin R4/d · scope: Backend
- L-4 · Commits pequenos · origin R5/e · scope: any
- L-5 · Escopo inválido vira any · origin R6/f · scope: banana
not a lesson
- R1 · not a lesson either
`;

{   // parse: scope field read and removed, origin dropped, no scope or unknown scope = any
  assert.deepEqual(parseLessons(TEXT), [
    { id: 'L-1', rule: 'Meça com o ESLint', scope: 'any' },
    { id: 'L-2', rule: 'Use `utils/x`', scope: 'frontend' },
    { id: 'L-3', rule: 'No `any` no backend', scope: 'backend' },
    { id: 'L-4', rule: 'Commits pequenos', scope: 'any' },
    { id: 'L-5', rule: 'Escopo inválido vira any', scope: 'any' },
  ]);
  assert.deepEqual(parseLessons(''), []);
}
{   // paths: the front's folder; a package with its own repository or a root folder gets **
  assert.equal(scopePaths('any', {}), null);
  assert.deepEqual(scopePaths('frontend', { FRONTEND_DIR: 'web/' }), ['web/**']);
  assert.deepEqual(scopePaths('backend', { BACKEND_DIR: 'api', BACKEND_OWN_REPO: '1' }), ['**'], 'own repository: worktree paths are package-relative');
  assert.deepEqual(scopePaths('backend', { BACKEND_DIR: '.' }), ['**']);
  assert.deepEqual(scopePaths('frontend', {}), ['**']);
}
{   // render: one file per scope with lessons; frontmatter only on scoped files; generated marker
  const files = renderRules(parseLessons(TEXT), { BACKEND_DIR: 'api', FRONTEND_DIR: 'web' }, 'docs/lessons.md');
  assert.deepEqual(Object.keys(files).sort(), ['ai-team-lessons-backend.md', 'ai-team-lessons-frontend.md', 'ai-team-lessons.md']);
  assert.ok(files['ai-team-lessons.md'].startsWith('<!-- generated by ai-team from docs/lessons.md'), 'no frontmatter: loads always');
  assert.match(files['ai-team-lessons.md'], /- L-1 · Meça com o ESLint\n- L-4 · Commits pequenos\n- L-5 · Escopo inválido vira any\n$/);
  assert.ok(files['ai-team-lessons-frontend.md'].startsWith('---\npaths:\n  - "web/**"\n---\n'));
  assert.match(files['ai-team-lessons-backend.md'], /- L-3 · No `any` no backend\n$/);
  assert.ok(!/origin/.test(Object.values(files).join('')), 'origin is not sent to the agents');
}
{   // sync on disk: writes, then a stat only; refresh when the lessons change; removes a scope left empty
  const proj = fs.mkdtempSync(path.join(os.tmpdir(), 'ai-team-lessons-'));
  fs.mkdirSync(path.join(proj, '.claude'), { recursive: true }); fs.mkdirSync(path.join(proj, 'docs'));
  fs.writeFileSync(path.join(proj, '.claude', 'ai-team.conf'), "DOCS_LESSONS='docs/lessons.md'\nFRONTEND_DIR='web'\nBACKEND_DIR='api'\n");
  const rules = path.join(proj, '.claude', 'rules'), src = path.join(proj, 'docs', 'lessons.md');
  assert.equal(syncLessonRules(proj), null, 'no lessons file yet: nothing');
  fs.writeFileSync(src, TEXT);
  assert.deepEqual(syncLessonRules(proj).written.sort(), ['ai-team-lessons-backend.md', 'ai-team-lessons-frontend.md', 'ai-team-lessons.md']);
  assert.equal(syncLessonRules(proj), null, 'unchanged: nothing to do');
  fs.writeFileSync(path.join(rules, 'mine.md'), '- my own rule\n');
  const later = new Date(Date.now() + 5000);
  fs.writeFileSync(src, '- L-1 · Só uma · origin R1/a · scope: frontend\n'); fs.utimesSync(src, later, later);
  const r = syncLessonRules(proj);
  assert.deepEqual(r.written, ['ai-team-lessons-frontend.md']);
  assert.deepEqual(r.removed.sort(), ['ai-team-lessons-backend.md', 'ai-team-lessons.md']);
  assert.ok(fs.existsSync(path.join(rules, 'mine.md')), "the project's own rules are never touched");
  assert.deepEqual(syncLessonRules(proj, { force: true }), { written: [], removed: [] }, 'force with the same content: nothing written');
  // SubagentStart refreshes them through the hook
  fs.writeFileSync(src, '- L-1 · Outra · origin R1/a\n'); const later2 = new Date(Date.now() + 10000); fs.utimesSync(src, later2, later2);
  runHook(JSON.stringify({ hook_event_name: 'SubagentStart', session_id: 's', agent_id: 'a', agent_type: 'builder' }), { env: { CLAUDE_PROJECT_DIR: proj, AI_TEAM_NOTIFY: '0', HOME: proj } });
  assert.ok(fs.existsSync(path.join(rules, 'ai-team-lessons.md')) && !fs.existsSync(path.join(rules, 'ai-team-lessons-frontend.md')), 'hook refreshed the rules');
  // no DOCS_LESSONS in the conf: nothing at all
  assert.equal(syncLessonRules(proj, { conf: {} }), null);
  fs.rmSync(proj, { recursive: true, force: true });
}

console.log('✓ lessons ok');
